#!/usr/bin/env bash
# Coverage gate for the Hack&Change case: > 80% of team-written application lines.
# Reports Go and frontend separately, excludes generated code, mocks and tests,
# writes reproducible reports to coverage/, and fails below COVERAGE_MIN.
#
# Env: COVERAGE_MIN (default 85), GO_DIR (default backend), FRONT_DIR (default frontend),
#      COVERAGE_EXCLUDE (extra extended regex of repo-relative Go paths to exclude, e.g. '^backend/cmd/')
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MIN=${COVERAGE_MIN:-85}
GO_DIR=${GO_DIR:-backend}
FRONT_DIR=${FRONT_DIR:-frontend}
OUT="$ROOT/coverage"
mkdir -p "$OUT"
status=0
report="$OUT/REPORT.md"
{
  echo "# Coverage report"
  echo
  echo "Generated by \`scripts/coverage-check.sh\` on $(date -u +%Y-%m-%dT%H:%MZ). Threshold: ${MIN}%."
  echo
  echo "| Part | Lines/statements covered | Report |"
  echo "|---|---|---|"
} >"$report"

below() { awk -v a="$1" -v b="$2" 'BEGIN { exit !(a + 0 < b + 0) }'; }

# ---------- Go ----------
if [ -f "$ROOT/$GO_DIR/go.mod" ]; then
  echo "==> Go ($GO_DIR)"
  if ! (cd "$ROOT/$GO_DIR" && go test ./... -count=1 -coverpkg=./... -coverprofile="$OUT/go.raw.out" >"$OUT/go.test.log" 2>&1); then
    tail -n 40 "$OUT/go.test.log"
    echo "    FAIL: Go tests failed (full log: coverage/go.test.log)"
    exit 1
  fi
  module=$(cd "$ROOT/$GO_DIR" && go list -m)
  # Decide per file whether it is excluded: generated, mocks, protobuf, or COVERAGE_EXCLUDE.
  excluded="$OUT/go.excluded.txt"
  : >"$excluded"
  tail -n +2 "$OUT/go.raw.out" | cut -d: -f1 | sort -u | while read -r f; do
    rel="${f#"$module"/}"
    path="$GO_DIR/$rel"
    if [[ "$rel" == *_mock.go || "$rel" == */mocks/* || "$rel" == *.pb.go ]] \
      || { [ -f "$ROOT/$path" ] && head -n 30 "$ROOT/$path" | grep -qE '^// Code generated .* DO NOT EDIT\.$'; } \
      || { [ -n "${COVERAGE_EXCLUDE:-}" ] && [[ "$path" =~ $COVERAGE_EXCLUDE ]]; }; then
      echo "$f" >>"$excluded"
    fi
  done
  awk -F: 'NR == FNR { skip[$0] = 1; next } FNR == 1 || !($1 in skip)' \
    "$excluded" "$OUT/go.raw.out" >"$OUT/go.out"
  (cd "$ROOT/$GO_DIR" && go tool cover -html="$OUT/go.out" -o "$OUT/go.html" \
    && go tool cover -func="$OUT/go.out" >"$OUT/go.func.txt")
  go_pct=$(tail -1 "$OUT/go.func.txt" | awk '{ gsub("%", "", $NF); print $NF }')
  echo "    Go total: ${go_pct}% (excluded files: $(wc -l <"$excluded"))"
  echo "| Go backend | ${go_pct}% of statements | coverage/go.html, coverage/go.func.txt |" >>"$report"
  if below "$go_pct" "$MIN"; then echo "    FAIL: Go coverage below ${MIN}%"; status=1; fi
else
  echo "==> Go: no $GO_DIR/go.mod, skipped"
fi

# ---------- Frontend ----------
if [ -f "$ROOT/$FRONT_DIR/package.json" ]; then
  echo "==> Frontend ($FRONT_DIR)"
  # Thresholds are disabled for this run so a non-zero exit means failing tests; the gate is applied below.
  if ! (cd "$ROOT/$FRONT_DIR" && npx vitest run --coverage --coverage.thresholds.lines=0 \
    --coverage.reporter=json-summary --coverage.reporter=html --coverage.reporter=text-summary \
    --coverage.reportsDirectory="$OUT/frontend" >"$OUT/frontend.test.log" 2>&1); then
    tail -n 40 "$OUT/frontend.test.log"
    echo "    FAIL: frontend tests failed (full log: coverage/frontend.test.log)"
    exit 1
  fi
  fe_pct=$(node -e 'console.log(require(process.argv[1]).total.lines.pct)' "$OUT/frontend/coverage-summary.json")
  echo "    Frontend lines: ${fe_pct}%"
  echo "| Frontend | ${fe_pct}% of lines | coverage/frontend/index.html |" >>"$report"
  if below "$fe_pct" "$MIN"; then echo "    FAIL: frontend coverage below ${MIN}%"; status=1; fi
else
  echo "==> Frontend: no $FRONT_DIR/package.json, skipped"
fi

{
  echo
  echo "Excluded: dependencies, test files, generated code (\`// Code generated ... DO NOT EDIT.\`), mocks, protobuf${COVERAGE_EXCLUDE:+, and paths matching \`$COVERAGE_EXCLUDE\`}."
  echo "Reproduce: \`make cover-check\` (or \`bash scripts/coverage-check.sh\`)."
} >>"$report"
echo "==> Report: coverage/REPORT.md"
exit $status
